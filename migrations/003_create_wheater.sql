CREATE TABLE weather_location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city VARCHAR(150) NOT NULL,
    state VARCHAR(150) NOT NULL,
    country VARCHAR(150) NOT NULL,
    latitude NUMERIC(9,6) NOT NULL,
    longitude NUMERIC(9,6) NOT NULL,

    CONSTRAINT uq_weather_location_coordinates
        UNIQUE (latitude, longitude),

    CONSTRAINT chk_weather_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_weather_longitude
        CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE historical_weather (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL
        REFERENCES weather_location(id),

    weather_date DATE NOT NULL,
    temperature_mean NUMERIC(5,2),
    precipitation_sum NUMERIC(8,2),

    CONSTRAINT uq_historical_weather
        UNIQUE (location_id, weather_date)
);

