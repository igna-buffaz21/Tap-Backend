BEGIN;

CREATE TABLE business (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT business_status_ck CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE branch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    name VARCHAR(200) NOT NULL,
    address TEXT,
    phone VARCHAR(50),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT branch_status_ck CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT branch_business_id_id_uq UNIQUE (business_id, id)
);

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clerk_id VARCHAR(255) UNIQUE,
    business_id BIGINT NOT NULL REFERENCES business(id),
    name VARCHAR(200) NOT NULL,
    email VARCHAR(255),
    role VARCHAR(50) NOT NULL DEFAULT 'EMPLOYEE',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT app_user_status_ck CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT app_user_business_id_id_uq UNIQUE (business_id, id)
);

CREATE TABLE user_branch (
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    branch_id BIGINT NOT NULL REFERENCES branch(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, branch_id)
);

CREATE TABLE customer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    name VARCHAR(200),
    phone VARCHAR(50),
    email VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT customer_status_ck CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT customer_business_id_id_uq UNIQUE (business_id, id)
);

CREATE TABLE product_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    name VARCHAR(200) NOT NULL,
    description TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT product_category_status_ck CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT product_category_business_id_id_uq UNIQUE (business_id, id)
);

CREATE TABLE product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    category_id BIGINT,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    sku VARCHAR(100),
    unit VARCHAR(30) NOT NULL DEFAULT 'unit',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    cost_price NUMERIC(14,4),
    sale_price NUMERIC(14,4),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT product_category_fk FOREIGN KEY (business_id, category_id)
        REFERENCES product_category(business_id, id),
    CONSTRAINT product_status_ck CHECK (status IN ('ACTIVE','INACTIVE')),
    CONSTRAINT product_cost_ck CHECK (cost_price IS NULL OR cost_price >= 0),
    CONSTRAINT product_sale_price_ck CHECK (sale_price IS NULL OR sale_price >= 0),
    CONSTRAINT product_business_id_id_uq UNIQUE (business_id, id),
    CONSTRAINT product_business_sku_uq UNIQUE (business_id, sku)
);

CREATE TABLE product_stock (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    branch_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity NUMERIC(14,3) NOT NULL DEFAULT 0,
    minimum_quantity NUMERIC(14,3) NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT product_stock_branch_fk FOREIGN KEY (business_id, branch_id)
        REFERENCES branch(business_id, id),
    CONSTRAINT product_stock_product_fk FOREIGN KEY (business_id, product_id)
        REFERENCES product(business_id, id),
    CONSTRAINT product_stock_quantity_ck CHECK (quantity >= 0),
    CONSTRAINT product_stock_minimum_ck CHECK (minimum_quantity >= 0),
    CONSTRAINT product_stock_business_branch_product_uq UNIQUE (business_id, branch_id, product_id)
);

CREATE TABLE sale (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    branch_id BIGINT NOT NULL,
    customer_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    subtotal NUMERIC(14,2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    notes TEXT,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT sale_branch_fk FOREIGN KEY (business_id, branch_id)
        REFERENCES branch(business_id, id),
    CONSTRAINT sale_customer_fk FOREIGN KEY (business_id, customer_id)
        REFERENCES customer(business_id, id),
    CONSTRAINT sale_user_fk FOREIGN KEY (business_id, created_by)
        REFERENCES app_user(business_id, id),
    CONSTRAINT sale_status_ck CHECK (status IN ('OPEN','COMPLETED','CANCELLED')),
    CONSTRAINT sale_subtotal_ck CHECK (subtotal >= 0),
    CONSTRAINT sale_discount_ck CHECK (discount_amount >= 0),
    CONSTRAINT sale_total_ck CHECK (total_amount >= 0),
    CONSTRAINT sale_business_id_id_uq UNIQUE (business_id, id)
);

-- Nota: al igual que el DER, sale_item no lleva business_id. La pertenencia
-- del producto al mismo business que la venta debe validarse en la capa de servicio.
CREATE TABLE sale_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sale(id),
    product_id BIGINT NOT NULL REFERENCES product(id),
    quantity NUMERIC(14,3) NOT NULL,
    unit_price NUMERIC(14,4) NOT NULL,
    subtotal NUMERIC(14,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT sale_item_quantity_ck CHECK (quantity > 0),
    CONSTRAINT sale_item_unit_price_ck CHECK (unit_price >= 0),
    CONSTRAINT sale_item_subtotal_ck CHECK (subtotal >= 0)
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL REFERENCES sale(id),
    amount NUMERIC(14,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT payment_amount_ck CHECK (amount >= 0),
    CONSTRAINT payment_status_ck CHECK (status IN ('PENDING','COMPLETED','FAILED','CANCELLED','REFUNDED'))
);

CREATE TABLE stock_movement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES business(id),
    branch_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    type VARCHAR(15) NOT NULL,
    quantity NUMERIC(14,3) NOT NULL,
    previous_quantity NUMERIC(14,3) NOT NULL,
    new_quantity NUMERIC(14,3) NOT NULL,
    reason VARCHAR(30) NOT NULL,
    notes TEXT,
    unit_price NUMERIC(14,4),
    created_by_user_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT stock_movement_branch_fk FOREIGN KEY (business_id, branch_id)
        REFERENCES branch(business_id, id),
    CONSTRAINT stock_movement_product_fk FOREIGN KEY (business_id, product_id)
        REFERENCES product(business_id, id),
    CONSTRAINT stock_movement_user_fk FOREIGN KEY (business_id, created_by_user_id)
        REFERENCES app_user(business_id, id),
    CONSTRAINT stock_movement_type_ck CHECK (type IN ('IN','OUT','ADJUSTMENT')),
    CONSTRAINT stock_movement_reason_ck CHECK (reason IN (
        'PURCHASE','SALE','INTERNAL_USE','LOSS','DAMAGE','RETURN',
        'MANUAL_ADJUSTMENT','OTHER'
    )),
    CONSTRAINT stock_movement_qty_ck CHECK (quantity > 0),
    CONSTRAINT stock_movement_previous_ck CHECK (previous_quantity >= 0),
    CONSTRAINT stock_movement_new_ck CHECK (new_quantity >= 0),
    CONSTRAINT stock_movement_price_ck CHECK (unit_price IS NULL OR unit_price >= 0)
);

-- Indices para accesos frecuentes y consultas por fecha/producto.
CREATE INDEX branch_business_idx ON branch(business_id);
CREATE INDEX app_user_business_idx ON app_user(business_id);
CREATE INDEX user_branch_branch_idx ON user_branch(branch_id);
CREATE INDEX customer_business_idx ON customer(business_id);
CREATE INDEX product_category_business_idx ON product_category(business_id);
CREATE INDEX product_business_category_idx ON product(business_id, category_id);
CREATE INDEX product_stock_product_idx ON product_stock(product_id);
CREATE INDEX sale_business_date_idx ON sale(business_id, created_at);
CREATE INDEX sale_branch_date_idx ON sale(branch_id, created_at);
CREATE INDEX sale_customer_idx ON sale(customer_id);
CREATE INDEX sale_item_sale_idx ON sale_item(sale_id);
CREATE INDEX sale_item_product_idx ON sale_item(product_id);
CREATE INDEX payment_sale_idx ON payment(sale_id);
CREATE INDEX stock_movement_product_date_idx ON stock_movement(product_id, created_at);
CREATE INDEX stock_movement_branch_date_idx ON stock_movement(branch_id, created_at);

COMMIT;
